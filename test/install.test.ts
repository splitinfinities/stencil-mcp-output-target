// The install script a production build of the fixture wrote (fixture/mcp/install.mjs), run in
// scratch projects the way a consumer runs it.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test, type TestContext } from 'node:test';
import { FIXTURE, ROOT } from './helpers.ts';

const SCRIPT = join(FIXTURE, 'mcp/install.mjs');

const ENTRY = { command: 'npx', args: ['-y', '-p', '@my/components', 'components-mcp'] };

/** An empty project, removed when the test ends. */
function project(t: TestContext): string {
  const dir = mkdtempSync(join(tmpdir(), 'mcp-install-'));

  t.after(() => rmSync(dir, { recursive: true, force: true }));

  return dir;
}

const install = (cwd: string, ...args: string[]) => spawnSync(process.execPath, [SCRIPT, ...args], { cwd, encoding: 'utf8' });

const json = (dir: string, file: string) => JSON.parse(readFileSync(join(dir, file), 'utf8'));

test('the script is the output target\'s, with the library\'s names on one line and no dependencies', () => {
  const script = readFileSync(SCRIPT, 'utf8');
  const template = readFileSync(join(ROOT, 'dist/install.mjs'), 'utf8');
  const line = /^const LIBRARY = .*$/m;

  assert.equal(readFileSync(join(ROOT, 'runtime/install.mjs'), 'utf8'), template);
  assert.equal(script.replace(line, ''), template.replace(line, ''));
  assert.match(script, /^const LIBRARY = \{"name":"components","package":"@my\/components","bin":"components-mcp"\};$/m);
  assert.match(readFileSync(join(FIXTURE, 'mcp-zero/install.mjs'), 'utf8'), /"bin":"components-mcp-zero"\};$/m);
  assert.ok(script.startsWith('#!/usr/bin/env node\n// Generated by stencil-mcp-output-target. Do not edit'));
  assert.deepEqual([...script.matchAll(/^import .* from '(.*)';$/gm)].map((match) => match[1]), ['node:fs', 'node:path', 'node:util']);
});

test('a project that shows no client gets .mcp.json, and a second run changes nothing', (t) => {
  const dir = project(t);
  const first = install(dir);

  assert.equal(first.status, 0, first.stderr);
  assert.match(first.stdout, /^components MCP server \(@my\/components\)\n {2}\.mcp\.json {2}added \(Claude Code\)\nRestart the client/);
  assert.deepEqual(readdirSync(dir), ['.mcp.json']);
  assert.equal(readFileSync(join(dir, '.mcp.json'), 'utf8'), `${JSON.stringify({ mcpServers: { components: ENTRY } }, null, 2)}\n`);

  const second = install(dir);

  assert.equal(second.status, 0);
  assert.match(second.stdout, /\.mcp\.json {2}already registered \(Claude Code\)\n$/);
});

test('it writes to the clients the project uses, each in its own shape', (t) => {
  const dir = project(t);

  mkdirSync(join(dir, '.cursor'));
  mkdirSync(join(dir, '.vscode'));
  writeFileSync(join(dir, 'GEMINI.md'), '');
  const result = install(dir);

  assert.equal(result.status, 0, result.stderr);
  assert.ok(!existsSync(join(dir, '.mcp.json')));
  assert.deepEqual(json(dir, '.cursor/mcp.json'), { mcpServers: { components: ENTRY } });
  assert.deepEqual(json(dir, '.vscode/mcp.json'), { servers: { components: { type: 'stdio', ...ENTRY } } });
  assert.deepEqual(json(dir, '.gemini/settings.json'), { mcpServers: { components: ENTRY } });
});

test('--client and --all pick the clients; an unknown one is refused', (t) => {
  const dir = project(t);

  mkdirSync(join(dir, '.cursor'));
  assert.equal(install(dir, '--client', 'vscode,claude').status, 0);
  assert.deepEqual([existsSync(join(dir, '.mcp.json')), existsSync(join(dir, '.vscode/mcp.json')), existsSync(join(dir, '.cursor/mcp.json'))], [true, true, false]);

  assert.equal(install(dir, '--all').status, 0);
  assert.ok(existsSync(join(dir, '.cursor/mcp.json')) && existsSync(join(dir, '.gemini/settings.json')));

  const unknown = install(dir, '--client', 'emacs');

  assert.equal(unknown.status, 2);
  assert.match(unknown.stderr, /^Unknown client emacs \(the clients are claude, cursor, vscode, gemini\)\./);
  assert.equal(install(dir, '--nope').status, 2);
});

test('it keeps the rest of a config and its indentation, and updates a stale entry', (t) => {
  const dir = project(t);
  const other = { command: 'node', args: ['other.js'] };

  writeFileSync(join(dir, '.mcp.json'), `${JSON.stringify({ mcpServers: { other, components: { command: 'node', args: ['old.mjs'] } }, extra: true }, null, '\t')}\n`);
  mkdirSync(join(dir, '.gemini'));
  writeFileSync(join(dir, '.gemini/settings.json'), '{ "theme": "dark" }\n');
  const result = install(dir);

  assert.match(result.stdout, /\.mcp\.json +updated \(Claude Code\)/);
  assert.match(result.stdout, /\.gemini\/settings\.json +added \(Gemini CLI\)/);
  assert.equal(readFileSync(join(dir, '.mcp.json'), 'utf8'), `${JSON.stringify({ mcpServers: { other, components: ENTRY }, extra: true }, null, '\t')}\n`);
  assert.deepEqual(json(dir, '.gemini/settings.json'), { theme: 'dark', mcpServers: { components: ENTRY } });
});

test('--dry-run writes nothing, --print prints the entry, --remove takes it out', (t) => {
  const dir = project(t);
  const dry = install(dir, '--dry-run');

  assert.match(dry.stdout, /\.mcp\.json {2}would be added \(Claude Code\)\n$/);
  assert.deepEqual(readdirSync(dir), []);

  assert.deepEqual(JSON.parse(install(dir, '--print').stdout), { mcpServers: { components: ENTRY } });
  assert.deepEqual(readdirSync(dir), []);
  assert.match(install(dir, '--help').stdout, /^Registers the components MCP server \(@my\/components\)/);

  writeFileSync(join(dir, '.mcp.json'), JSON.stringify({ mcpServers: { other: {}, components: ENTRY } }));
  assert.match(install(dir, '--remove').stdout, /\.mcp\.json {2}removed \(Claude Code\)/);
  assert.deepEqual(json(dir, '.mcp.json'), { mcpServers: { other: {} } });
  assert.match(install(dir, '--remove').stdout, /\.mcp\.json {2}not registered \(Claude Code\)\n$/);
  // Removing from a client the project never configured creates nothing.
  assert.match(install(dir, '--remove', '--client', 'cursor').stdout, /not registered \(Cursor\)/);
  assert.ok(!existsSync(join(dir, '.cursor')));
});

test('a config it can\'t edit safely is left alone, with the entry to add by hand', (t) => {
  const dir = project(t);
  const commented = '{\n  // my servers\n  "servers": {}\n}\n';

  mkdirSync(join(dir, '.vscode'));
  writeFileSync(join(dir, '.vscode/mcp.json'), commented);
  writeFileSync(join(dir, '.mcp.json'), '{ "mcpServers": [] }');
  const result = install(dir);

  assert.equal(result.status, 1);
  assert.match(result.stdout, /\.mcp\.json +skipped: the file "mcpServers" isn't an object\. Add it by hand: "mcpServers": \{"components":\{"command":"npx"/);
  assert.match(result.stdout, /\.vscode\/mcp\.json +skipped: the file isn't plain JSON \(comments\?\)\. Add it by hand: "servers": \{"components":\{"type":"stdio"/);
  assert.equal(readFileSync(join(dir, '.vscode/mcp.json'), 'utf8'), commented);
  assert.equal(readFileSync(join(dir, '.mcp.json'), 'utf8'), '{ "mcpServers": [] }');
});
